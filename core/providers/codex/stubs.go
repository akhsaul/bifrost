// accumulateResponsesStream drains a responses stream channel into one unary
// responses response. The terminal response.completed event carries the full
// response, so it is preferred verbatim; when the stream ends without one
// (deltas only), the text deltas concatenate into a single output message.
// The first error chunk aborts the drain and surfaces as the unary error.
//
// Raw capture rides along: the terminal chunk carries ExtraFields.RawRequest
// (the wire body, set by the openai streaming helper when capture is on) and
// every chunk carries its raw SSE frame in ExtraFields.RawResponse. Both are
// folded into the returned response so logging (store_raw_request_response)
// and send-back see them. Without this the unary fan-in path would return a
// response with empty RawRequest/RawResponse even when capture was enabled.
func accumulateResponsesStream(stream chan *schemas.BifrostStreamChunk, model string) (*schemas.BifrostResponsesResponse, *schemas.BifrostError) {
	var (
		completed  *schemas.BifrostResponsesResponse
		text       strings.Builder
		id         *string
		created    int
		respModel  string
		usage      *schemas.ResponsesResponseUsage
		extra      schemas.BifrostResponseExtraFields
		rawRequest interface{}
		rawFrames  []string
		sawChunk   bool
	)
	for chunk := range stream {
		if chunk == nil {
			continue
		}
		if chunk.BifrostError != nil && chunk.BifrostError.Error != nil {
			return nil, chunk.BifrostError
		}
		ev := chunk.BifrostResponsesStreamResponse
		if ev == nil {
			continue
		}
		sawChunk = true
		switch ev.Type {
		case schemas.ResponsesStreamResponseTypeCompleted, schemas.ResponsesStreamResponseTypeIncomplete:
			if ev.Response != nil {
				completed = ev.Response
			}
		case schemas.ResponsesStreamResponseTypeOutputTextDelta:
			if ev.Delta != nil {
				text.WriteString(*ev.Delta)
			}
			if ev.Response != nil {
				if id == nil && ev.Response.ID != nil {
					id = ev.Response.ID
				}
				if ev.Response.Model != "" {
					respModel = ev.Response.Model
				}
				if ev.Response.Usage != nil {
					usage = ev.Response.Usage
				}
			}
		case schemas.ResponsesStreamResponseTypeOutputItemDone:
			if ev.Item != nil && ev.Item.Content != nil && ev.Item.Content.ContentStr != nil {
				text.WriteString(*ev.Item.Content.ContentStr)
			}
		}
		if ev.Response != nil && ev.Response.Usage != nil {
			usage = ev.Response.Usage
		}
		extra.Latency = ev.ExtraFields.Latency
		if ev.ExtraFields.ProviderResponseHeaders != nil {
			extra.ProviderResponseHeaders = ev.ExtraFields.ProviderResponseHeaders
		}
		if ev.ExtraFields.RawRequest != nil && rawRequest == nil {
			rawRequest = ev.ExtraFields.RawRequest
		}
		if ev.ExtraFields.RawResponse != nil {
			if s, ok := ev.ExtraFields.RawResponse.(string); ok {
				rawFrames = append(rawFrames, s)
			} else if b, err := sonic.Marshal(ev.ExtraFields.RawResponse); err == nil {
				rawFrames = append(rawFrames, string(b))
			}
		}
	}
	// attachRaw folds the collected raw capture into extra. RawResponse joins
	// the raw SSE frames like the streaming accumulator does, stored as
	// json.RawMessage so it serializes as raw bytes (unary convention) rather
	// than a quoted string.
	attachRaw := func(extra *schemas.BifrostResponseExtraFields) {
		if rawRequest != nil && extra.RawRequest == nil {
			extra.RawRequest = rawRequest
		}
		if len(rawFrames) > 0 && extra.RawResponse == nil {
			extra.RawResponse = json.RawMessage(strings.Join(rawFrames, "\n\n"))
		}
	}
	if completed != nil {
		if completed.ExtraFields.Latency == 0 {
			completed.ExtraFields.Latency = extra.Latency
		}
		if completed.ExtraFields.ProviderResponseHeaders == nil {
			completed.ExtraFields.ProviderResponseHeaders = extra.ProviderResponseHeaders
		}
		attachRaw(&completed.ExtraFields)
		return completed, nil
	}
	if !sawChunk {
		return &schemas.BifrostResponsesResponse{Model: model, ExtraFields: extra}, nil
	}
	out := &schemas.BifrostResponsesResponse{
		Model:       model,
		Usage:       usage,
		ExtraFields: extra,
	}
	attachRaw(&out.ExtraFields)
	if id != nil {
		out.ID = id
	}
	if respModel != "" {
		out.Model = respModel
	}
	out.CreatedAt = created
	content := text.String()
	out.Output = []schemas.ResponsesMessage{
		{
			Role:    schemas.Ptr(schemas.ResponsesInputMessageRoleAssistant),
			Content: &schemas.ResponsesMessageContent{ContentStr: &content},
		},
	}
	return out, nil
}

