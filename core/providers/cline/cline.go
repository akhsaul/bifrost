// Package cline implements the Cline provider, an OpenAI-compatible gateway
// at https://api.cline.bot/api.
//
// Two things make it unlike the plain OpenAI-compatible providers:
//
//   - Every call must carry Cline client-identity headers (user-agent,
//     http-referer, x-client-*, x-platform-*, x-task-id, x-title). They are
//     defaults that operators may override via extra_headers.
//   - Non-streaming chat completions arrive wrapped in an envelope:
//     {"data": {<openai chat completion>}, "success": true}. Streaming is
//     standard OpenAI SSE.
//   - ListModels merges two endpoints: /v1/models (OpenAI shape) and
//     /v1/ai/cline/recommended-models (custom shape).
//   - Auth is dual-mode: a static API key in Key.Value is sent verbatim as
//     "Bearer <value>", while ClineKeyConfig carries a WorkOS-device-flow
//     refresh token that is exchanged for a short-lived access token sent as
//     "Bearer workos:<access_token>".
package cline

import (
	"context"
	"strings"
	"time"

	"github.com/maximhq/bifrost/core/providers/openai"
	providerUtils "github.com/maximhq/bifrost/core/providers/utils"
	schemas "github.com/maximhq/bifrost/core/schemas"
	"github.com/valyala/fasthttp"
)

// ClineProvider implements the Provider interface for Cline's API.
type ClineProvider struct {
	logger              schemas.Logger        // Logger for provider operations
	client              *fasthttp.Client      // HTTP client for unary API requests (ReadTimeout bounds overall response)
	streamingClient     *fasthttp.Client      // HTTP client for streaming API requests (no ReadTimeout; idle governed by NewIdleTimeoutReader)
	networkConfig       schemas.NetworkConfig // Network configuration including extra headers
	sendBackRawRequest  bool                  // Whether to include raw request in BifrostResponse
	sendBackRawResponse bool                  // Whether to include raw response in BifrostResponse
	chatPath            string
	modelsPath          string
	recommendedPath     string
	refreshPath         string
}

// NewClineProvider creates a new Cline provider instance.
func NewClineProvider(config *schemas.ProviderConfig, logger schemas.Logger) (*ClineProvider, error) {
	config.CheckAndSetDefaults()

	requestTimeout := time.Second * time.Duration(config.NetworkConfig.DefaultRequestTimeoutInSeconds)
	client := &fasthttp.Client{
		ReadTimeout:         requestTimeout,
		WriteTimeout:        requestTimeout,
		MaxConnsPerHost:     config.NetworkConfig.MaxConnsPerHost,
		MaxIdleConnDuration: time.Second * time.Duration(config.NetworkConfig.KeepAliveTimeoutInSeconds),
		MaxConnWaitTimeout:  requestTimeout,
		MaxConnDuration:     time.Second * time.Duration(schemas.DefaultMaxConnDurationInSeconds),
		ConnPoolStrategy:    fasthttp.FIFO,
	}

	client = providerUtils.ConfigureProxy(client, config.ProxyConfig, logger)
	client = providerUtils.ConfigureDialer(client, config.NetworkConfig.AllowPrivateNetwork)
	client = providerUtils.ConfigureTLS(client, config.NetworkConfig, logger)
	streamingClient := providerUtils.BuildStreamingClient(client)

	if config.NetworkConfig.BaseURL == "" {
		config.NetworkConfig.BaseURL = DefaultBaseURL
	}
	config.NetworkConfig.BaseURL = strings.TrimRight(config.NetworkConfig.BaseURL, "/")

	return &ClineProvider{
		logger:              logger,
		client:              client,
		streamingClient:     streamingClient,
		networkConfig:       config.NetworkConfig,
		sendBackRawRequest:  config.SendBackRawRequest,
		sendBackRawResponse: config.SendBackRawResponse,
		chatPath:            "/v1/chat/completions",
		modelsPath:          "/v1/models",
		recommendedPath:     "/v1/ai/cline/recommended-models",
		refreshPath:         "/v1/auth/refresh",
	}, nil
}

// GetProviderKey returns the provider identifier for Cline.
func (provider *ClineProvider) GetProviderKey() schemas.ModelProvider {
	return schemas.Cline
}

// resolveAuth resolves the Authorization header value for one request and
// reports whether OAuth mode was used (true) or a static key (false).
func (provider *ClineProvider) resolveAuth(ctx *schemas.BifrostContext, key schemas.Key) (string, bool, *schemas.BifrostError) {
	return resolveCredentials(ctx, key, provider.client, provider.networkConfig.BaseURL+provider.refreshPath)
}

// doChatCompletion runs one chat completion attempt with the given auth value.
func (provider *ClineProvider) doChatCompletion(ctx *schemas.BifrostContext, authValue string, key schemas.Key, request *schemas.BifrostChatRequest) (*schemas.BifrostChatResponse, *schemas.BifrostError) {
	return openai.HandleOpenAIChatCompletionRequest(
		ctx,
		provider.client,
		provider.networkConfig.BaseURL+providerUtils.GetPathFromContext(ctx, provider.chatPath),
		request,
		map[string]string{"Authorization": authValue},
		BuildHeaders(ctx, provider.networkConfig.ExtraHeaders, request),
		providerUtils.ShouldSendBackRawRequest(ctx, provider.sendBackRawRequest),
		providerUtils.ShouldSendBackRawResponse(ctx, provider.sendBackRawResponse),
		provider.GetProviderKey(),
		clineChatResponseHandler,
		parseClineError,
		nil,
		provider.logger,
	)
}

// ChatCompletion performs a chat completion request to the Cline API.
func (provider *ClineProvider) ChatCompletion(ctx *schemas.BifrostContext, key schemas.Key, request *schemas.BifrostChatRequest) (*schemas.BifrostChatResponse, *schemas.BifrostError) {
	authValue, isOAuth, bErr := provider.resolveAuth(ctx, key)
	if bErr != nil {
		return nil, bErr
	}
	resp, err := provider.doChatCompletion(ctx, authValue, key, request)
	if err != nil && isOAuth && isUnauthorized(err) {
		// The cached access token died (or was never valid). Drop it and retry
		// once with a freshly minted one before surfacing the 401.
		invalidateCredentials(&key)
		if authValue, _, bErr = provider.resolveAuth(ctx, key); bErr != nil {
			return nil, bErr
		}
		return provider.doChatCompletion(ctx, authValue, key, request)
	}
	return resp, err
}

// doChatCompletionStream runs one streaming chat completion attempt.
func (provider *ClineProvider) doChatCompletionStream(ctx *schemas.BifrostContext, postHookRunner schemas.PostHookRunner, postHookSpanFinalizer func(context.Context), authValue string, key schemas.Key, request *schemas.BifrostChatRequest) (chan *schemas.BifrostStreamChunk, *schemas.BifrostError) {
	return openai.HandleOpenAIChatCompletionStreaming(
		ctx,
		provider.streamingClient,
		provider.networkConfig.BaseURL+providerUtils.GetPathFromContext(ctx, provider.chatPath),
		request,
		map[string]string{"Authorization": authValue},
		BuildHeaders(ctx, provider.networkConfig.ExtraHeaders, request),
		provider.networkConfig.StreamIdleTimeoutInSeconds,
		providerUtils.ShouldSendBackRawRequest(ctx, provider.sendBackRawRequest),
		providerUtils.ShouldSendBackRawResponse(ctx, provider.sendBackRawResponse),
		provider.GetProviderKey(),
		postHookRunner,
		nil,
		nil,
		parseClineError,
		nil,
		nil,
		nil,
		provider.logger,
		postHookSpanFinalizer,
	)
}

// ChatCompletionStream performs a streaming chat completion request to the Cline API.
// Cline streams standard OpenAI SSE, so no response handler is needed.
func (provider *ClineProvider) ChatCompletionStream(ctx *schemas.BifrostContext, postHookRunner schemas.PostHookRunner, postHookSpanFinalizer func(context.Context), key schemas.Key, request *schemas.BifrostChatRequest) (chan *schemas.BifrostStreamChunk, *schemas.BifrostError) {
	authValue, isOAuth, bErr := provider.resolveAuth(ctx, key)
	if bErr != nil {
		return nil, bErr
	}
	stream, err := provider.doChatCompletionStream(ctx, postHookRunner, postHookSpanFinalizer, authValue, key, request)
	if err != nil && isOAuth && isUnauthorized(err) {
		invalidateCredentials(&key)
		if authValue, _, bErr = provider.resolveAuth(ctx, key); bErr != nil {
			return nil, bErr
		}
		return provider.doChatCompletionStream(ctx, postHookRunner, postHookSpanFinalizer, authValue, key, request)
	}
	return stream, err
}

// Responses performs a responses request by converting through chat completions.
// Cline exposes no native /v1/responses endpoint (it answers 404), so converting
// is the only shape that works.
func (provider *ClineProvider) Responses(ctx *schemas.BifrostContext, key schemas.Key, request *schemas.BifrostResponsesRequest) (*schemas.BifrostResponsesResponse, *schemas.BifrostError) {
	chatResponse, err := provider.ChatCompletion(ctx, key, request.ToChatRequest())
	if err != nil {
		return nil, err
	}
	return chatResponse.ToBifrostResponsesResponse(), nil
}

// ResponsesStream performs a streaming responses request by converting through chat completions.
func (provider *ClineProvider) ResponsesStream(ctx *schemas.BifrostContext, postHookRunner schemas.PostHookRunner, postHookSpanFinalizer func(context.Context), key schemas.Key, request *schemas.BifrostResponsesRequest) (chan *schemas.BifrostStreamChunk, *schemas.BifrostError) {
	ctx.SetValue(schemas.BifrostContextKeyIsResponsesToChatCompletionFallback, true)
	return provider.ChatCompletionStream(
		ctx,
		postHookRunner,
		postHookSpanFinalizer,
		key,
		request.ToChatRequest(),
	)
}

